// 盘面操作 / 交易指令禁词(与首页 PRD §9.2 + 生成 prompt 禁语一致)。
// 违反即判非合规 → 调用方回退到模板/规则(构造式合规内容)。
// 2.1-W3 扩表(2026-07-07 拍板)+ 二轮 N1 / 三轮 T3 修正:
// - 「有效率」【裸禁】+ 白名单剥离正常语用(见 INDUSTRIAL_WHITELIST 的 更有效率/有效率地 族)。
//   三轮 review 实证:二轮的窄前瞻([约达为是] 单连接字)放行了"映射有效率很高/达到七成"等
//   副词型胜率断言——正是要禁的类,且无 hasSpecificMove 兜底。裸禁+白名单才关得死。
// - 「强受益」豁免 较/更/增 前缀:"较强受益逻辑"=「受益逻辑较强」的正常表述;"XX 强受益" 仍禁。
// - 受益确定/有效信号 保持裸禁(无正常语境)。
// 注:负责人清单里的裸「追」未收——会误伤「追踪/追溯/追加投资」等正常词,
// 交易语境的 追高/追涨/追板 已覆盖;「放量下杀/缩量企稳」等复合词由 放量/缩量/企稳/杀跌 单词覆盖。
const BANNED =
  /买入|卖出|建议买|建议卖|推荐买|抄底|满仓|加仓|减仓|清仓|低吸|接飞刀|站岗|目标价|建议参与|短线机会|回调关注|等回调|上车|别急着接|往里冲|追高|追涨|追板|低开|高开|企稳|放量|缩量|破位|补跌|超跌反弹|止跌|杀跌|洗盘|获利盘|兑现盘|错杀|出货|值得多看一眼|开盘盯|盘中盯|逢低|逢高|埋伏|潜伏|梭哈|梭一把|上车|下车|割肉|套牢|接盘|止损|止盈|建仓|补仓|重仓|半仓|空仓|打板|(?<![较更增])强受益|受益确定|有效率|有效信号/g;

// 产业语义白名单:先剥离这些合法用法,再扫禁词(如「出货量」「放量节奏」是产业指标,非盘面;
// 「更有效率/有效率地」是效率表述,非胜率断言——T3 起「有效率」裸禁,正常语用全靠这里放行)
const INDUSTRIAL_WHITELIST =
  /出货量|放量节奏|订单放量|业务放量|产品放量|真正放量|批量出货|出货节奏|出货预期|出货占比|产能放量|开始出货|加速出货|规模出货|更有效率|更加有效率|更为有效率|有效率地|变得有效率/g;

export function scanBannedWords(text: string): string[] {
  const cleaned = text.replace(INDUSTRIAL_WHITELIST, "");
  const hits = cleaned.match(BANNED) ?? [];
  return Array.from(new Set(hits));
}

// 「成」作涨跌单位(涨两成)与作比率/成词(毛利率三成 / 成功)歧义大——先剥离【非涨跌】的
// 数字+成 语境(比率/一成不变/九成新),再统一半/全/中文数字判「数字+成」;末尾负向前瞻排除
// 成词首字(功/交/本…,但【不含就】,否则「两成就见顶」被躲漏)。修 B2-11 引入的净回归。
const CHENG_METRIC =
  /一成不变|[零一二三四五六七八九十两0-9０-９]+\s*成\s*新|[毛净]利率[约达在为]?\s*[零一二三四五六七八九十两0-9０-９]+\s*成|(占比?|市占率|渗透率|份额|市场份额|中签率|转化率|命中率)[约达在为]?\s*[零一二三四五六七八九十两0-9０-９]*\s*成/g;

// 具体涨跌数字红线:半角 + 全角 + 中文数字(「涨了三个点」「涨了５%」「回撤3成」「两成就见顶」都算)。
export function hasSpecificMove(t: string): boolean {
  const chengClean = t.replace(CHENG_METRIC, ""); // 剥离比率/成词语境后再判「数字+成」
  return (
    /\d+(\.\d+)?\s*[%％]/.test(t) || // 半角/全角 %:5% / 5％
    /\d+\s*个\s*多?\s*点/.test(t) || // 5个多点
    /(涨|跌)\s*了?\s*\d/.test(t) || // 涨了3
    /[０-９]+(?:[.．][０-９]+)?\s*[%％点]/.test(t) || // 全角数字 + %/点
    /(涨|跌)\s*了?\s*[０-９]/.test(t) || // 涨了５
    /(涨|跌)\s*了?\s*[一二三四五六七八九十两]+\s*[%％]/.test(t) || // 涨了三%
    /[一二三四五六七八九十两]+\s*个\s*多?\s*点/.test(t) || // 三个点/三个多点(去强制涨跌前缀)
    /[0-9０-９一二三四五六七八九十两]+\s*成(?![功交本色语员品型套批长熟])/.test(chengClean) || // 数字+成(半/全/中文统一;排成词首字,不含就)
    /百分之\s*[0-9０-９一二三四五六七八九十两]+/.test(t) || // 百分之五
    /[0-9０-９一二三四五六七八九十两]+\s*个\s*百分点/.test(t) // 三个百分点
  );
}

// 一次性合规判定(生成后 / 发布前用):既无禁词、也无具体涨跌数字才算干净。
export function isComplianceClean(text: string): {
  ok: boolean;
  bannedHits: string[];
  hasNumber: boolean;
} {
  const bannedHits = scanBannedWords(text);
  const hasNumber = hasSpecificMove(text);
  return { ok: bannedHits.length === 0 && !hasNumber, bannedHits, hasNumber };
}
